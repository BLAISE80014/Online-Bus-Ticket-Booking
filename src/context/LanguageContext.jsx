const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(
    () => localStorage.getItem("appLanguage") || "en",
  );

  const changeLanguage = useCallback((nextLanguage) => {
    if (!translations[nextLanguage]) {
      throw new Error(`Unsupported language: ${nextLanguage}`);
    }
    localStorage.setItem("appLanguage", nextLanguage);
    document.documentElement.lang = nextLanguage;
    setLanguage(nextLanguage);
    window.dispatchEvent(new CustomEvent("app-language-change"));
  }, []);

  const value = useMemo(
    () => ({
      language,
      changeLanguage,
      t: (text) => translations[language]?.[text] || text,
    }),
    [language, changeLanguage],
  );

  React.useEffect(() => {
    document.documentElement.lang = language;
    const syncLanguage = () => {
      const savedLanguage = localStorage.getItem("appLanguage") || "en";
      if (translations[savedLanguage]) setLanguage(savedLanguage);
    };
    window.addEventListener("storage", syncLanguage);
    return () => window.removeEventListener("storage", syncLanguage);
  }, [language]);

  return (
    <LanguageContext.Provider value={value}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used within LanguageProvider");
  }
  return context;
}
